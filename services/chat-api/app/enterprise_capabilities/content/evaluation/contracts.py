"""Data structures for the dynamic-standards evaluation pipeline.

Three concepts only:
    - Standard: a single criterion the content must satisfy. Generated by an
      LLM from the user's request alone (no content is shown to the
      generator) so the standard stays objective.
    - Issue:    a specific failure to meet a standard. Found by another LLM
      that reads the content with standards as the rubric.
    - EvaluationResult: the bundle returned to the caller. Includes the
      generated standards (so they can be displayed/edited in UI later),
      the list of issues, the verdict, and — if a repair was applied — the
      repaired content.
"""
from __future__ import annotations

from typing import Any, Dict, List, Literal, Optional

from pydantic import BaseModel, Field


Severity = Literal["critical", "major", "minor"]
Verdict = Literal["pass", "needs_repair", "needs_rewrite"]


class Standard(BaseModel):
    """One verifiable criterion the deliverable must meet."""

    id: str  # e.g. "std_001" — assigned at generation time
    severity: Severity
    description: str  # one-line, MUST be objectively verifiable
    anti_example: str = ""  # optional: what failing this standard looks like


class Issue(BaseModel):
    """A specific spot where the content fails a standard."""

    standard_id: str  # references Standard.id
    severity: Severity  # carries the standard's severity for quick triage
    location: str  # section name / paragraph hint / "全文" if span-wide
    finding: str  # what's wrong, concretely
    fix_suggestion: str  # how to fix, concretely


class EvaluationResult(BaseModel):
    standards: List[Standard] = Field(default_factory=list)
    issues: List[Issue] = Field(default_factory=list)
    verdict: Verdict = "pass"
    repaired_content: Optional[str] = None
    repair_applied: bool = False
    metadata: Dict[str, Any] = Field(default_factory=dict)


def derive_verdict(issues: List[Issue]) -> Verdict:
    """Pure function: severity → verdict. No score arithmetic."""
    has_critical = any(i.severity == "critical" for i in issues)
    has_major = any(i.severity == "major" for i in issues)
    if has_critical:
        return "needs_rewrite"
    if has_major:
        return "needs_repair"
    return "pass"
